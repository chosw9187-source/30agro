/**
 * 사내 역량평가 양식의 **첫 연도판 밑그림**.
 *
 * 인사팀이 준 엑셀 여섯 벌(직무 23종 · 115문항)과 PDF 한 장(핵심가치 5문항)을
 * 그대로 옮겨 둔 것이다. 관리 화면의 「사내 양식으로 채우기」가 이 값을 한 번
 * 심고, 그 뒤로는 **DB가 원본**이다 — 문항을 고치는 곳은 화면이고 이 파일이
 * 아니다. 매년 바뀌는 문항을 코드에 두면 인사팀이 개발자를 찾아와야 한다.
 *
 * 열쇠(`key`)는 해를 넘겨도 이어진다. 연도판을 복사할 때 그대로 옮기므로,
 * 직무 이름을 나중에 바꿔도 열쇠는 그대로 둔다 — 열쇠가 바뀌면 지난해 점수가
 * 어느 문항 것이었는지 알 수 없게 된다.
 */

export type CompetencySeedItem = {
  key: string;
  area: string;
  question: string;
};

export type CompetencySeedSet = {
  /** 「인사팀」·「지점」처럼 직무 이름. */
  name: string;
  items: CompetencySeedItem[];
  /**
   * 이 직무를 기본값으로 씌울 팀 이름. 한 팀에 직무가 여럿인 곳(관리·생산·경영지원)은
   * 대표 하나만 기본으로 두고, 나머지는 사람별 예외로 지정한다.
   */
  teams: string[];
  /** 이름이 이것으로 끝나는 팀 전부에 씌운다 — 지점 열한 곳이 한 벌을 함께 쓴다. */
  teamNameEndsWith?: string;
  /** 화면에서 손봐야 할 것이 있으면 적어 둔다. */
  note?: string;
};

